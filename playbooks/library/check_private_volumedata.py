from ansible.module_utils.basic import *

DOCUMENTATION='''
    This module parses the raw commandline output generated by the privatevolumedata operation performed on an SVC to fetch the
    volume name and is hence ready to unmap.
'''

def run_module():
    returnValue = dict()
    try:
        fields = {
                "privatevolume_data":{"required":True,"type":"list"},
        }
        module = AnsibleModule(argument_spec = fields)
        volumes = module.params["privatevolume_data"]
        privatevolumes = []
        volume_uid = []
        volume_scsi_id =[]
        for i in volumes:
            privatevolumes.append(i["vdisk_name"])
            volume_uid.append(i["vdisk_UID"])
            volume_scsi_id.append(i["SCSI_id"])
        returnValue["data"] =  privatevolumes
        returnValue["uid"] =  volume_uid
        returnValue["scsi"] =  volume_scsi_id
        module.exit_json(**returnValue)
    except Exception as e:
        returnValue["msg"] = "[Error] "+str(e)
        module.fail_json(**returnValue)        

if __name__=='__main__':
    run_module()
