from ansible.module_utils.basic import *

DOCUMENTATION='''
    This module parses the raw commandline output generated by the lsvdiskhostmap operation performed on an SVC to check that the
    volume isn't mapped to any other hosts or hostclusters and is hence ready for decommissioning.
'''

def run_module():
    returnValue = dict()
    try:
        fields = {
                "lsvdisk_output":{"required":True,"type":"list"},
        }
        module = AnsibleModule(argument_spec = fields)
        dataset = [{"volname":result["inner_item"],"lines":result["stdout_lines"]} for idx,result in enumerate(module.params["lsvdisk_output"])]
        for data in dataset:
            if data["lines"][0] == "[]":
                data["rename"] = True
            else:
                data["rename"] = False
        returnValue["data"] = dataset 
        module.exit_json(**returnValue)
    except Exception as e:
        returnValue["msg"] = "[Error] "+str(e)
        module.fail_json(**returnValue)        

if __name__=='__main__':
    run_module()
