from ansible.module_utils.basic import *

DOCUMENTATION='''
    This module parses the raw commandline output generated by the renamevolumeoutputs operation performed on an SVC to check that the
    the unmapped volume has renamed successfully.
'''

def run_module():
    returnValue = dict()
    try:
        fields = {
                "rename_output":{"required":True,"type":"list"},
        }
        module = AnsibleModule(argument_spec = fields)
        renameout = []
        rename_success = []
        for data in module.params["rename_output"]:
            renameout.append(data["changed"])
        
        for j in renameout:
            if j == True:
                rename_success.append("true")
            else:
                rename_success.append("false")
        if len(renameout) == len(rename_success) and "false" not in rename_success:
            returnValue["data"] = "success" 
            module.exit_json(**returnValue)
        else:
            returnValue["data"] = "fails" 
            module.exit_json(**returnValue)

    except Exception as e:
        returnValue["msg"] = "[Error] "+str(e)
        module.fail_json(**returnValue)        

if __name__=='__main__':
    run_module()
