from ansible.module_utils.basic import *

DOCUMENTATION='''
    This module parses the raw commandline output generated by the hostcountdata operation performed on an SVC to check the
    host count in the cluster.
'''

def run_module():
    returnValue = dict()
    try:
        fields = {
                "hostcount_data":{"required":True,"type":"list"},
        }
        module = AnsibleModule(argument_spec = fields)
        host_count = module.params["hostcount_data"]
        new_list = [item for item in host_count if item]
        if len(new_list) == 1:
            for i in new_list:
                hostcount = i["host_count"]
        else:
            hostcount = False
        returnValue["data"] =  hostcount
        module.exit_json(**returnValue)
    except Exception as e:
        returnValue["msg"] = "[Error] "+str(e)
        module.fail_json(**returnValue)        

if __name__=='__main__':
    run_module()
