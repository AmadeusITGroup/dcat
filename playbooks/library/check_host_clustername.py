from ansible.module_utils.basic import *

DOCUMENTATION='''
   This module parses the raw commandline output generated by the hostclusterdata operation performed on an SVC to check that the
   host is part of host cluster.
'''

def run_module():
    returnValue = dict()
    try:
        fields = {
                "hostcluster_data":{"required":True,"type":"dict"},
        }
        module = AnsibleModule(argument_spec = fields)
        host_cluster = module.params["hostcluster_data"]
        wwpns = []
        for i in host_cluster["nodes"]:
            wwpns.append(i["WWPN"])
        returnValue["data"] =  host_cluster["host_cluster_name"]
        returnValue["wwpns"] =  wwpns
        returnValue["status"] =  host_cluster["status"]
        module.exit_json(**returnValue)
    except Exception as e:
        returnValue["msg"] = "[Error] "+str(e)
        module.fail_json(**returnValue)        

if __name__=='__main__':
    run_module()
