from ansible.module_utils.basic import *

DOCUMENTATION='''
    This module parses the raw commandline output generated by the unmap_output operation performed on an SVC to check all
    the volumes has unmapped successfully.
'''

def run_module():
    returnValue = dict()
    try:
        fields = {
                "unmap_data":{"required":True,"type":"list"},
        }
        module = AnsibleModule(argument_spec = fields)
        volumes = module.params["unmap_data"]
        private_unmap = []
        cleared = []
        not_unmapped = []
        for i in volumes:
            private_unmap.append(i["msg"])

        for i in private_unmap:
            if "deleted" in i:
                cleared.append("True")
            else:
                cleared.append("False")
                not_unmapped.append(i)

        if len(private_unmap) == len(cleared) and "False" not in cleared:
            returnValue["data"] = "success"
            returnValue["unmapped_volumes"] = "All Volumes are unmapped"
            module.exit_json(**returnValue)
        else:
            returnValue["data"] = "failure"
            returnValue["unmapped_volumes"] = not_unmapped
            module.exit_json(**returnValue)

    except Exception as e:
        returnValue["msg"] = "[Error] "+str(e)
        module.fail_json(**returnValue)        

if __name__=='__main__':
    run_module()
