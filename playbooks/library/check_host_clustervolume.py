from ansible.module_utils.basic import *

DOCUMENTATION='''
    This module parses the raw commandline output generated by the host_cluster_volume operation performed on an SVC to fetch the
    host cluster volume name and is hence ready to unmap.
'''

def run_module():
    returnValue = dict()
    try:
        fields = {
                "hostcluster_volume":{"required":True,"type":"list"},
        }
        module = AnsibleModule(argument_spec = fields)
        hostcluster_volume = module.params["hostcluster_volume"]
        clustervolume = []
        clustervolume_uid = []
        clustervolume_scsi = []
        for i in hostcluster_volume:
            clustervolume.append(i["volume_name"]) 
            clustervolume_uid.append(i["volume_UID"])
            clustervolume_scsi.append(i["SCSI_id"])
        returnValue["data"] =  clustervolume
        returnValue["uid"] =  clustervolume_uid
        returnValue["scsi"] =  clustervolume_scsi
        module.exit_json(**returnValue)
    except Exception as e:
        returnValue["msg"] = "[Error] "+str(e)
        module.fail_json(**returnValue)        

if __name__=='__main__':
    run_module()
